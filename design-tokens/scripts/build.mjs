// Builds design tokens (W3C DTCG 2025.10) into Swift, Jetpack Compose and CSS with Style Dictionary 5.
import StyleDictionary from "style-dictionary";
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const pkg = join(here, "..");
const repo = join(pkg, "..");
const staging = join(pkg, ".build");
const check = process.argv.includes("--check");

const rem = (v) => {
  if (!v || typeof v !== "object" || v.unit !== "rem") throw new Error(`dimension must be {value, unit:"rem"}: ${JSON.stringify(v)}`);
  return v.value * 16;
};
const ms = (v) => {
  if (!v || typeof v !== "object") throw new Error(`duration must be {value, unit}: ${JSON.stringify(v)}`);
  return v.unit === "s" ? v.value * 1000 : v.value;
};
const isFontSize = (t) => t.$type === "dimension" && t.path[0] === "font" && t.path[1] === "size";

StyleDictionary.registerTransform({
  name: "trivia/compose/size", type: "value", transitive: true,
  filter: (t) => t.$type === "dimension",
  transform: (t) => `${rem(t.$value).toFixed(2)}.${isFontSize(t) ? "sp" : "dp"}`,
});
StyleDictionary.registerTransform({
  name: "trivia/compose/duration", type: "value", transitive: true,
  filter: (t) => t.$type === "duration",
  transform: (t) => `${ms(t.$value)}L`,
});
StyleDictionary.registerTransform({
  name: "trivia/swift/duration", type: "value", transitive: true,
  filter: (t) => t.$type === "duration",
  transform: (t) => `TimeInterval(${(ms(t.$value) / 1000).toFixed(3)})`,
});

const swiftTransforms = ["attribute/cti", "name/camel", "color/UIColorSwift", "content/swift/literal", "asset/swift/literal", "size/swift/remToCGFloat", "trivia/swift/duration"];
const composeTransforms = ["attribute/cti", "name/camel", "color/composeColor", "trivia/compose/size", "trivia/compose/duration"];
const header = "Generated by design-tokens/scripts/build.mjs from DTCG 2025.10 sources. Do not edit.";

const native = (t) => t.$type !== "fontFamily"; // native apps use the platform system font
const top = (...names) => (t) => names.includes(t.path[0]);

// One Style Dictionary run per scope keeps light/dark names identical (theme.*) across themes.
const scopes = [
  { name: "Base", sources: ["primitives"], filter: top("space", "radius", "touch", "font", "motion"), cssSelector: ":root" },
  { name: "Light", sources: ["primitives", "theme-light"], filter: top("theme"), cssSelector: ":root" },
  { name: "Dark", sources: ["primitives", "theme-dark"], filter: top("theme"), cssSelector: ':root[data-theme="dark"]' },
  { name: "Overlay", sources: ["primitives", "overlay"], filter: top("overlay"), cssSelector: ":root" },
];

// Final destinations inside the platform projects.
const targets = (scope) => [
  { platform: "swift", file: `Tokens${scope}.swift`, dest: "ios/Packages/Core/Sources/DesignSystem/Generated" },
  { platform: "compose", file: `Tokens${scope}.kt`, dest: "android/core/designsystem/src/main/kotlin/al/trivia/core/designsystem/generated" },
  { platform: "css", file: `tokens-${scope.toLowerCase()}.css`, dest: "web-consoles/packages/ui/src/tokens" },
];

rmSync(staging, { recursive: true, force: true });
for (const s of scopes) {
  const sd = new StyleDictionary({
    source: s.sources.map((f) => join(pkg, "tokens", `${f}.tokens.json`)),
    usesDtcg: true,
    log: { verbosity: "silent", warnings: "disabled" },
    platforms: {
      swift: {
        transforms: swiftTransforms, buildPath: join(staging, "swift") + "/",
        files: [{ destination: `Tokens${s.name}.swift`, format: "ios-swift/class.swift", filter: (t) => s.filter(t) && native(t),
          options: { className: `Tokens${s.name}`, accessControl: "public", fileHeader: () => [header] } }],
      },
      compose: {
        transforms: composeTransforms, buildPath: join(staging, "compose") + "/",
        files: [{ destination: `Tokens${s.name}.kt`, format: "compose/object", filter: (t) => s.filter(t) && native(t),
          options: { className: `Tokens${s.name}`, packageName: "al.trivia.core.designsystem.generated", fileHeader: () => [header] } }],
      },
      css: {
        transformGroup: "css", buildPath: join(staging, "css") + "/",
        files: [{ destination: `tokens-${s.name.toLowerCase()}.css`, format: "css/variables", filter: s.filter,
          options: { selector: s.cssSelector, outputReferences: false, fileHeader: () => [header] } }],
      },
    },
  });
  await sd.buildAllPlatforms();
}

// Web: also follow the OS dark-mode preference unless the page forces light (data-theme="light").
{
  const dark = readFileSync(join(staging, "css", "tokens-dark.css"), "utf8")
    .replace(':root[data-theme="dark"]', ':root:not([data-theme="light"])');
  const body = dark.slice(dark.indexOf(":root"));
  writeFileSync(join(staging, "css", "tokens-dark-auto.css"),
    `/**\n * ${header}\n */\n@media (prefers-color-scheme: dark) {\n${body.replace(/^/gm, "  ").trimEnd()}\n}\n`);
  scopes.push({ name: "Dark-auto", webOnly: true });
}

let stale = 0;
for (const s of scopes) {
  for (const t of targets(s.name).filter((t) => !s.webOnly || t.platform === "css")) {
    const generated = readFileSync(join(staging, t.platform, t.file), "utf8");
    const out = join(repo, t.dest, t.file);
    if (check) {
      if (!existsSync(out) || readFileSync(out, "utf8") !== generated) { console.error("stale:", out); stale++; }
    } else {
      mkdirSync(dirname(out), { recursive: true });
      writeFileSync(out, generated);
      console.log("wrote", join(t.dest, t.file));
    }
  }
}
rmSync(staging, { recursive: true, force: true });
if (stale) { console.error(`${stale} generated file(s) stale: run npm run build in design-tokens/`); process.exit(1); }
if (check) console.log("generated token files are up to date");
